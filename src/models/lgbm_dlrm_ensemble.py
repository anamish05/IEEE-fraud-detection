import numpy as np
import pandas as pd
from scipy.stats import rankdata
from sklearn.metrics import roc_auc_score, average_precision_score, recall_score

def rank_norm_blend_oof(
    lgb_oof_preds: np.ndarray,
    dlrm_oof_preds: np.ndarray,
    y_true: np.ndarray,
    oof_mask: np.ndarray,
    weight_steps: int = 21
):
    """
    Finds optimal rank-normalized blend weights for Out-Of-Fold predictions
    generated by TimeSeriesSplit.
    
    Parameters:
    -----------
    lgb_oof_preds  : np.ndarray, shape (N,)
    dlrm_oof_preds : np.ndarray, shape (N,)
    y_true         : np.ndarray, shape (N,)
    oof_mask       : np.ndarray (bool), shape (N,) where True marks rows that
                     fell into a validation split in at least one fold.
    """
    # 1. Filter strictly to rows evaluated during CV
    y_eval = y_true[oof_mask]
    lgb_eval = lgb_oof_preds[oof_mask]
    dlrm_eval = dlrm_oof_preds[oof_mask]
    n_samples = len(y_eval)

    # 2. Convert raw model scores to percentile ranks [0.0, 1.0]
    lgb_ranked = rankdata(lgb_eval) / n_samples
    dlrm_ranked = rankdata(dlrm_eval) / n_samples

    # Standalone baseline metrics
    lgb_roc = roc_auc_score(y_eval, lgb_eval)
    dlrm_roc = roc_auc_score(y_eval, dlrm_eval)
    lgb_pr = average_precision_score(y_eval, lgb_eval)
    dlrm_pr = average_precision_score(y_eval, dlrm_eval)
    lgb_recall = recall_score(y_eval, lgb_eval)
    dlrm_recall = recall_score(y_eval, dlrm_eval)

    # 3. Grid search blend weight w * LGB + (1 - w) * DLRM
    weights_lgb = np.linspace(0.0, 1.0, weight_steps)
    results = []
    best_roc = -1.0
    best_w = None

    for w_lgb in weights_lgb:
        w_dlrm = 1.0 - w_lgb
        blended = (w_lgb * lgb_ranked) + (w_dlrm * dlrm_ranked)
        
        roc = roc_auc_score(y_eval, blended)
        pr = average_precision_score(y_eval, blended)
        recall = recall_score(y_eval, blended)
        delta_roc = roc - lgb_roc

        results.append({
            "w_lgb": round(w_lgb, 2),
            "w_dlrm": round(w_dlrm, 2),
            "roc_auc": roc,
            "pr_auc": pr,
            "recall":recall,
            "delta_vs_lgb": delta_roc
        })

        if roc > best_roc:
            best_roc = roc
            best_w = (round(w_lgb, 2), round(w_dlrm, 2))

    results_df = pd.DataFrame(results)
    best_delta = best_roc - lgb_roc

    return results_df, best_w, best_roc, best_delta, (lgb_roc, dlrm_roc, lgb_pr, dlrm_pr, lgb_recall, dlrm_recall)


